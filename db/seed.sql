-- Rafaela: 3 meses de ponto -----------------------------------------------
-- Dias úteis dos últimos 3 meses, fora feriados, as férias (há 64 a 58 dias)
-- e as ausências aprovadas (há 40 e 15 dias). Hoje fica livre para bater o
-- ponto na demonstração. As variações saem de um hash da data, então são as
-- mesmas a cada restauração: entrada 07:50–08:11 e, em ~1 a cada 9 dias,
-- atraso até 08:45; almoço de 55 a 70 min; saída 17:00–17:25, com hora extra
-- (18:30–19:30) ou saída mais cedo (16:15–16:45); e alguns dias sem a saída.
CREATE TEMPORARY TABLE TMP_DIAS_RAFAELA AS
WITH RECURSIVE dias AS (
  SELECT CURDATE() - INTERVAL 92 DAY AS dia
  UNION ALL SELECT dia + INTERVAL 1 DAY FROM dias WHERE dia < CURDATE() - INTERVAL 1 DAY
)
SELECT dia,
  -- CRC32 é sem sinal: sem o CAST, o saldo negativo estoura
  CAST(CASE WHEN CRC32(CONCAT(dia, 'a')) % 9 = 0 THEN 30000 + CRC32(CONCAT(dia, 'b')) % 1500
            ELSE 28200 + CRC32(CONCAT(dia, 'b')) % 1260 END AS SIGNED) AS entrada,
  CAST(43200 + CRC32(CONCAT(dia, 'c')) % 1200 AS SIGNED) AS inicio_almoco,
  CAST(3300 + CRC32(CONCAT(dia, 'd')) % 900 AS SIGNED) AS almoco,
  CAST(CASE CRC32(CONCAT(dia, 'e')) % 6
            WHEN 0 THEN 66600 + CRC32(CONCAT(dia, 'f')) % 3600
            WHEN 1 THEN 58500 + CRC32(CONCAT(dia, 'f')) % 1800
            ELSE 61200 + CRC32(CONCAT(dia, 'f')) % 1500 END AS SIGNED) AS saida,
  CRC32(CONCAT(dia, 'g')) % 23 = 0 AS sem_saida
FROM dias
WHERE DAYOFWEEK(dia) NOT IN (1, 7)
  AND dia NOT IN (SELECT DAT_FERIADO FROM FERIADO)
  AND dia NOT BETWEEN CURDATE() - INTERVAL 64 DAY AND CURDATE() - INTERVAL 58 DAY
  AND dia NOT IN (CURDATE() - INTERVAL 40 DAY, CURDATE() - INTERVAL 15 DAY);

INSERT INTO REGISTRO_PONTO (ID_USUARIO, DATA_REGISTRO, HORA_REGISTRO, ID_TIPO_REGISTRO_PONTO, LOCALIZACAO)
SELECT 1, t.dia,
       TIMESTAMP(t.dia, SEC_TO_TIME(CASE k.tipo WHEN 1 THEN t.entrada WHEN 2 THEN t.inicio_almoco
                                                WHEN 3 THEN t.inicio_almoco + t.almoco ELSE t.saida END)),
       k.tipo, 'Escritório (dados de teste)'
  FROM TMP_DIAS_RAFAELA t
  CROSS JOIN (SELECT 1 AS tipo UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4) k
 WHERE NOT (k.tipo = 4 AND t.sem_saida);

-- Saldo de cada dia contra a jornada de 8h; sem a saída, o dia fica inconsistente
