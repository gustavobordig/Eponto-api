-- Esquema do banco do ePonto, reconstruído a partir do SQL dos repositórios
-- (Data/Repositories) e dos modelos em Domain, em out/2026. O repositório não
-- tinha o esquema: as tabelas só existiam no banco do Railway. Antes de usar
-- este arquivo como referência de produção, compare com `SHOW CREATE TABLE` de lá.
--
-- Uso local: veja db/README.md.

CREATE DATABASE IF NOT EXISTS eponto CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS eponto_hangfire CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE eponto;

-- Pessoas ------------------------------------------------------------------

CREATE TABLE PERFIL (
  ID_PERFIL                        INT AUTO_INCREMENT PRIMARY KEY,
  DSC_PERFIL                       VARCHAR(100) NOT NULL,
  IND_ACESSO_ADMIN                 TINYINT NOT NULL DEFAULT 0,  -- 1 = token com role Admin
  IND_PERMITE_CADASTRAR            TINYINT NOT NULL DEFAULT 0,
  IND_PERMITE_EDITAR               TINYINT NOT NULL DEFAULT 0,
  IND_PERMITE_DELETAR              TINYINT NOT NULL DEFAULT 0,
  IND_PERMITE_REGULAR_SOLICITACOES TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE CARGO (
  ID_CARGO        INT AUTO_INCREMENT PRIMARY KEY,
  NOME_CARGO      VARCHAR(100) NOT NULL,
  SALARIO         DECIMAL(10,2) NOT NULL,
  FORMACAO_MINIMA VARCHAR(100),
  IND_ATIVO       TINYINT NOT NULL DEFAULT 1
);

CREATE TABLE JORNADA_TRABALHO (
  ID_JORNADA        INT AUTO_INCREMENT PRIMARY KEY,
  NOME_JORNADA      VARCHAR(100) NOT NULL,
  QTD_HORAS_DIARIAS INT NOT NULL,
  IND_ATIVO         TINYINT NOT NULL DEFAULT 1
);

CREATE TABLE USUARIO (
  ID_USUARIO      INT AUTO_INCREMENT PRIMARY KEY,
  NOME            VARCHAR(150) NOT NULL,
  DATA_NASCIMENTO DATE,
  SENHA           VARCHAR(100) NOT NULL,             -- hash BCrypt
  EMAIL           VARCHAR(150) NOT NULL UNIQUE,
  ID_CARGO        INT NOT NULL,
  ID_JORNADA      INT NOT NULL,
  TELEFONE        BIGINT,
  FOTO_PERFIL     LONGTEXT,                           -- base64 ou URL
  ID_CHEFE        INT,
  IND_ATIVO       TINYINT NOT NULL DEFAULT 1,
  DATA_CADASTRO   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ID_CARGO) REFERENCES CARGO (ID_CARGO),
  FOREIGN KEY (ID_JORNADA) REFERENCES JORNADA_TRABALHO (ID_JORNADA),
  FOREIGN KEY (ID_CHEFE) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE PERFIL_USUARIO (
  ID_USUARIO INT NOT NULL,
  ID_PERFIL  INT NOT NULL,
  PRIMARY KEY (ID_USUARIO, ID_PERFIL),
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL (ID_PERFIL)
);

-- Login e recuperação de senha (a mesma tabela guarda os dois)
CREATE TABLE LOGIN (
  ID_LOGIN        INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO      INT NOT NULL,
  TOKEN           TEXT,
  COD_RECUPERACAO INT,
  DAT_LOGIN       DATETIME NOT NULL,
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- Ponto e banco de horas ---------------------------------------------------

-- ID_TIPO_REGISTRO_PONTO: 1 entrada, 2 início do almoço, 3 fim do almoço, 4 saída
CREATE TABLE REGISTRO_PONTO (
  ID_REGISTRO            INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO             INT NOT NULL,
  HORA_REGISTRO          DATETIME NOT NULL,
  DATA_REGISTRO          DATE NOT NULL,
  ID_TIPO_REGISTRO_PONTO INT NOT NULL,
  LOCALIZACAO            VARCHAR(500),
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  INDEX IX_REGISTRO_USUARIO_DATA (ID_USUARIO, DATA_REGISTRO)
);

-- STATUS_SOLICITACAO: 0 pendente, 1 aprovada, 2 reprovada
CREATE TABLE SOLICITACAO_AJUSTE_PONTO (
  ID_SOLICITACAO          INT AUTO_INCREMENT PRIMARY KEY,
  ID_SOLICITANTE          INT NOT NULL,
  JUSTIFICATIVA           TEXT,
  STATUS_SOLICITACAO      INT NOT NULL DEFAULT 0,
  DATA_SOLICITACAO        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DATA_REGISTRO_ALTERACAO DATE,
  DATA_RESPOSTA           DATETIME,
  OBSERVACAO_RESPOSTA     VARCHAR(500),                 -- comentário de quem aprovou ou reprovou
  LOCALIZACAO             VARCHAR(500),
  FOREIGN KEY (ID_SOLICITANTE) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE ITEM_AJUSTE_PONTO (
  ID_ITEM                INT AUTO_INCREMENT PRIMARY KEY,
  ID_SOLICITACAO         INT NOT NULL,
  HORA_REGISTRO          DATETIME,
  ID_TIPO_REGISTRO_PONTO INT NOT NULL,
  LOCALIZACAO            VARCHAR(500),
  FOREIGN KEY (ID_SOLICITACAO) REFERENCES SOLICITACAO_AJUSTE_PONTO (ID_SOLICITACAO) ON DELETE CASCADE
);

CREATE TABLE VALIDACOES_MENSAIS (
  ID_VALIDACAO     INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO       INT NOT NULL,
  MES_REFERENCIA   INT NOT NULL,
  ANO_REFERENCIA   INT NOT NULL,
  STATUS_VALIDACAO INT NOT NULL,
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- Saldos em TIME, que aceita valor negativo (SEC_TO_TIME / TIME_TO_SEC no repositório)
CREATE TABLE BANCO_HORAS (
  ID_BANCO_HORAS    INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO        INT NOT NULL UNIQUE,              -- ON DUPLICATE KEY UPDATE
  HORAS_TRABALHADAS TIME NOT NULL DEFAULT '00:00:00',
  SALDO             TIME NOT NULL DEFAULT '00:00:00',
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE SALDO_DIARIO_BANCO_HORAS (
  ID_SALDO_DIARIO_BANCO_HORAS INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO                  INT NOT NULL,
  SALDO_DIARIO                TIME NOT NULL,
  DATA_REFERENCIA             DATE NOT NULL,
  APONTAMENTO_INCONSISTENTE   TINYINT NOT NULL DEFAULT 0,
  IND_ATIVO                   TINYINT NOT NULL DEFAULT 0, -- 1 = dia abonado (ausência aprovada)
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- Feriados e férias --------------------------------------------------------

-- TIPO_FERIADO: 1 integral, 2 meio período
CREATE TABLE FERIADO (
  ID_FERIADO   INT AUTO_INCREMENT PRIMARY KEY,
  DSC_FERIADO  VARCHAR(150) NOT NULL,
  DAT_FERIADO  DATE NOT NULL,
  TIPO_FERIADO INT NOT NULL DEFAULT 1
);

-- ID_USUARIO NULL = férias coletivas (da empresa)
CREATE TABLE FERIAS (
  ID_FERIAS         INT AUTO_INCREMENT PRIMARY KEY,
  DSC_FERIAS        VARCHAR(150) NOT NULL,
  DAT_INICIO_FERIAS DATE NOT NULL,
  DAT_FIM_FERIAS    DATE NOT NULL,
  ID_USUARIO        INT,
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- IND_SITUACAO: 0 pendente, 1 aprovada, 2 reprovada
CREATE TABLE SOLICITACAO_FERIAS (
  ID_SOLICITACAO_FERIAS INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO            INT NOT NULL,
  DSC_OBSERVACAO        VARCHAR(500),
  DAT_INICIO_FERIAS     DATE NOT NULL,
  DAT_FIM_FERIAS        DATE NOT NULL,
  DAT_SOLICITACAO       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  IND_SITUACAO          INT NOT NULL DEFAULT 0,
  OBSERVACAO_RESPOSTA   VARCHAR(500),                   -- comentário de quem aprovou ou reprovou
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE SALDO_FERIAS (
  ID_USUARIO INT PRIMARY KEY,
  QTD_SALDO  INT NOT NULL DEFAULT 0,
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- Solicitações -------------------------------------------------------------

-- STATUS_SOLICITACAO: 0 pendente, 1 aprovada, 2 reprovada
CREATE TABLE SOLICITACAO_AUSENCIA (
  ID_SOLICITACAO_AUSENCIA INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO              INT NOT NULL,
  LINK_ARQUIVO            VARCHAR(500),
  MENSAGEM_SOLICITACAO    TEXT,
  DATA_INICIO_AUSENCIA    DATETIME NOT NULL,
  DATA_FIM_AUSENCIA       DATETIME NOT NULL,
  DATA_SOLICITACAO        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  STATUS_SOLICITACAO      INT NOT NULL DEFAULT 0,
  OBSERVACAO_RESPOSTA     VARCHAR(500),                 -- comentário de quem aprovou ou reprovou
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- STATUS: 0 pendente, 1 respondida (o enum StatusFeedback da API tem os nomes trocados)
CREATE TABLE SOLICITACAO_FEEDBACK (
  ID_SOLICITACAO_FEEDBACK INT AUTO_INCREMENT PRIMARY KEY,
  ID_USUARIO_SOLICITACAO  INT NOT NULL,
  ID_RESPONSAVEL_FEEDBACK INT NOT NULL,
  STATUS                  INT NOT NULL DEFAULT 0,
  DATA_SOLICITACAO        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MENSAGEM_SOLICITACAO    TEXT,
  FOREIGN KEY (ID_USUARIO_SOLICITACAO) REFERENCES USUARIO (ID_USUARIO),
  FOREIGN KEY (ID_RESPONSAVEL_FEEDBACK) REFERENCES USUARIO (ID_USUARIO)
);

-- AVALIACAO: 0 péssimo … 4 excelente (FeedbackAvaliacao)
CREATE TABLE FEEDBACK (
  ID_FEEDBACK             INT AUTO_INCREMENT PRIMARY KEY,
  ID_SOLICITACAO_FEEDBACK INT,
  ID_USUARIO_FEEDBACK     INT NOT NULL,   -- quem recebe
  ID_AUTOR_FEEDBACK       INT NOT NULL,   -- quem escreve
  DATA_REALIZACAO         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MENSAGEM_FEEDBACK       TEXT,
  AVALIACAO               INT NOT NULL,
  FOREIGN KEY (ID_SOLICITACAO_FEEDBACK) REFERENCES SOLICITACAO_FEEDBACK (ID_SOLICITACAO_FEEDBACK) ON DELETE SET NULL,
  FOREIGN KEY (ID_USUARIO_FEEDBACK) REFERENCES USUARIO (ID_USUARIO),
  FOREIGN KEY (ID_AUTOR_FEEDBACK) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE COMUNICADO (
  ID_COMUNICADO       INT AUTO_INCREMENT PRIMARY KEY,
  TITULO_COMUNICADO   VARCHAR(150) NOT NULL,
  DSC_COMUNICADO      TEXT,
  DAT_INICIO_EXIBICAO DATETIME NOT NULL,
  DAT_FIM_EXIBICAO    DATETIME NOT NULL
);
